def _rows(project, sql):
    conn = sqlite3.connect(project / "test.sqlite3")
    try:
        return conn.execute(sql).fetchall()
    finally:
        conn.close()


def test_db_configure_scaffolds_migrations(project):
    result = runner.invoke(cli_app, ["db:configure"])
    assert result.exit_code == 0, result.output
    assert (project / "database" / "migrations" / "env.py").exists()
    assert (project / "database" / "migrations" / "script.py.mako").exists()
    assert (project / "database" / "migrations" / "versions").is_dir()


def test_full_migrate_lifecycle(project):
    assert runner.invoke(cli_app, ["db:configure"]).exit_code == 0

    made = runner.invoke(cli_app, ["make:migration", "create_posts_table"])
    assert made.exit_code == 0, made.output
    versions = list((project / "database" / "migrations" / "versions").glob("*.py"))
    assert len(versions) == 1
    source = versions[0].read_text()
    # Autogenerate picked up the posts table from the declared model.
    assert "create_table" in source
    assert "posts" in source

    migrated = runner.invoke(cli_app, ["migrate"])
    assert migrated.exit_code == 0, migrated.output
    assert _rows(project, "SELECT count(*) FROM posts") == [(0,)]

    rolled = runner.invoke(cli_app, ["migrate:rollback"])
    assert rolled.exit_code == 0, rolled.output
    assert _rows(project, "SELECT count(*) FROM sqlite_master WHERE name='posts'") == [(0,)]

    # Re-migrate then seed.
    assert runner.invoke(cli_app, ["migrate"]).exit_code == 0
    seeded = runner.invoke(cli_app, ["db:seed"])
    assert seeded.exit_code == 0, seeded.output
    assert _rows(project, "SELECT title FROM posts") == [("seeded",)]


def test_rollback_reverts_the_last_batch(project):
    """migrate:rollback reverts everything the last `migrate` applied."""
    assert runner.invoke(cli_app, ["db:configure"]).exit_code == 0

    # Batch 1: posts.
    assert runner.invoke(cli_app, ["make:migration", "create_posts_table"]).exit_code == 0
    assert runner.invoke(cli_app, ["migrate"]).exit_code == 0

    # Batch 2: comments (a second model + migration).
    comment_pkg = project / "app" / "modules" / "comment"
    (comment_pkg / "models").mkdir(parents=True)
    (comment_pkg / "__init__.py").write_text("")
    (comment_pkg / "models" / "__init__.py").write_text("")
    (comment_pkg / "models" / "comment.py").write_text(
        "from fastplace.orm import Field, Model\n"
        "\n"
        "class Comment(Model):\n"
        "    __tablename__ = 'comments'\n"
        "    id: int = Field(primary_key=True)\n"
        "    body: str = ''\n"
    )
    made_comments = runner.invoke(cli_app, ["make:migration", "create_comments_table"])
    assert made_comments.exit_code == 0, made_comments.output
    # Framework bookkeeping tables never leak into autogenerated diffs.
    second = sorted((project / "database" / "migrations" / "versions").glob("*.py"))[-1]
    assert "fastplace_migrations" not in second.read_text()

    assert runner.invoke(cli_app, ["migrate"]).exit_code == 0
    assert _rows(project, "SELECT count(*) FROM sqlite_master WHERE name='comments'") == [(1,)]

    # First rollback reverts batch 2 only.
    assert runner.invoke(cli_app, ["migrate:rollback"]).exit_code == 0
    assert _rows(project, "SELECT count(*) FROM sqlite_master WHERE name='comments'") == [(0,)]
    assert _rows(project, "SELECT count(*) FROM sqlite_master WHERE name='posts'") == [(1,)]

    # Second rollback reverts batch 1.
    assert runner.invoke(cli_app, ["migrate:rollback"]).exit_code == 0
    assert _rows(project, "SELECT count(*) FROM sqlite_master WHERE name='posts'") == [(0,)]


_HAND_WRITTEN = '''"""{name}

Revision ID: {rev}
Revises: {down}
"""
from alembic import op
import sqlalchemy as sa

revision: str = '{rev}'
down_revision = {down!r}
branch_labels = None
depends_on = None


def upgrade() -> None:
    op.create_table('{table}',
    sa.Column('id', sa.Integer(), nullable=False),
    sa.PrimaryKeyConstraint('id'))


def downgrade() -> None:
    op.drop_table('{table}')
'''


def test_migrate_applies_pending_set_as_one_batch(project):
    """Multiple pending revisions applied by ONE `migrate` = one rollback batch."""
    assert runner.invoke(cli_app, ["db:configure"]).exit_code == 0
    versions = project / "database" / "migrations" / "versions"
    (versions / "aaa1_first.py").write_text(
        _HAND_WRITTEN.format(name="first", rev="aaa1", down=None, table="batch_a")
    )
    (versions / "bbb2_second.py").write_text(
        _HAND_WRITTEN.format(name="second", rev="bbb2", down="aaa1", table="batch_b")
    )

    assert runner.invoke(cli_app, ["migrate"]).exit_code == 0
    assert _rows(project, "SELECT count(*) FROM sqlite_master WHERE name='batch_a'") == [(1,)]
    assert _rows(project, "SELECT count(*) FROM sqlite_master WHERE name='batch_b'") == [(1,)]

    # One rollback reverts the whole batch — both pending revisions.
    rolled = runner.invoke(cli_app, ["migrate:rollback"])
    assert rolled.exit_code == 0, rolled.output
    assert _rows(project, "SELECT count(*) FROM sqlite_master WHERE name='batch_a'") == [(0,)]
    assert _rows(project, "SELECT count(*) FROM sqlite_master WHERE name='batch_b'") == [(0,)]


